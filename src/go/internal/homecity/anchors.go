// anchors.go carries the default city/district anchor table. Anchors resolve a
// GPS start to a city vote by nearest-anchor-within-radius: no polygons, no
// external service, deterministic and dependency-free.
//
// Coverage policy: full prefecture-level granularity for the regions STRIDE
// users actually run (Shanghai metro, Jiangsu/Zhejiang/Anhui, Shandong,
// Sichuan, Yunnan, Hebei, Pearl River Delta) plus every provincial capital and
// major city elsewhere. Points more than MaxAnchorDistanceKM from any anchor
// are discarded rather than force-assigned, so an uncovered prefecture degrades
// to "no vote", never to a wrong city.
//
// For nationwide district-level precision swap Options.Anchors for a polygon
// boundary dataset; the table below is the curated default, and district
// anchors inside metros (青浦/朱家角, 呈贡, 都江堰…) exist precisely because
// nearest-city-center voting misassigns border suburbs (a 朱家角 start is 30 km
// from Kunshan's center but 40+ km from People's Square — city-center voting
// would read it as Suzhou).
package homecity

// Anchor is one named reference point. City is the administrative (prefecture)
// name used as the vote key; District refines it for metro areas; names are in
// the anchor table's own naming ("上海市" / "青浦区"), matching what the watch
// writes into activity names so the two vote sources aggregate cleanly.
type Anchor struct {
	Province  string
	City      string
	District  string
	Latitude  float64
	Longitude float64
}

func anchorCity(a Anchor) string { return a.City }

// nearestAnchor returns the closest anchor and its distance in kilometres;
// whether that distance is acceptable (MaxAnchorDistanceKM) is the caller's
// call. ok is false only for an empty table.
func nearestAnchor(anchors []Anchor, lat, lon float64) (Anchor, float64, bool) {
	best := Anchor{}
	bestDistance := 0.0
	found := false
	for _, a := range anchors {
		d := haversineKM(lat, lon, a.Latitude, a.Longitude)
		if !found || d < bestDistance {
			best, bestDistance, found = a, d, true
		}
	}
	return best, bestDistance, found
}

// DefaultAnchors returns the curated anchor table (copy per call so callers
// may mutate their Options safely).
func DefaultAnchors() []Anchor {
	anchors := append([]Anchor(nil), defaultAnchors...)
	return anchors
}

